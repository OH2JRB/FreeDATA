"""
Per-station message encryption (AES-256-GCM with pre-shared keys).

Encryption is off by default and switched on per station. Both operators
agree on a key outside the radio link and enter it in their GUI. Keys are only
held in server memory (StationKeyStore) and are never written to disk or sent
over the air, so the GUI asks for them again after a server restart.

With the "common key" setting ([MESSAGES] enable_common_key) on, messages to
and from every station are encrypted with one shared key. A station's own key
takes precedence over the common key.

LEGAL NOTE: most amateur radio regulations (e.g. ITU RR 25.2A, FCC 97.113(a)(4))
prohibit messages encoded to obscure their meaning. Only use this on
frequencies and under licences that allow encrypted traffic.

Wire format of an encrypted payload:

    version (1 byte) | nonce (12 bytes) | ciphertext + GCM tag (16 bytes)

The version byte is also used as associated data, so it cannot be changed
without the authentication failing.
"""

import hashlib
import os
import re
import threading

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

FORMAT_VERSION = 1
KEY_BYTES = 32
NONCE_BYTES = 12
TAG_BYTES = 16
OVERHEAD_BYTES = 1 + NONCE_BYTES + TAG_BYTES

MIN_PASSPHRASE_LENGTH = 12

# Both stations have to derive the same key from a passphrase, so the salt is
# a fixed, FreeDATA specific value. Use a random hex key for best security.
_PASSPHRASE_SALT = b"FreeDATA station key v1"
_HEX_KEY_RE = re.compile(r"^[0-9a-fA-F]{64}$")


class DecryptionError(Exception):
    """Raised when a payload can't be decrypted (wrong key or corrupt data)."""


class KeyMissingError(Exception):
    """Raised when a station's key is needed but has not been entered."""


def parse_key(key_text: str) -> bytes:
    """Converts user input to a 256 bit key.

    Accepts either 64 hex characters (a raw key, as generated by the GUI) or a
    passphrase of at least MIN_PASSPHRASE_LENGTH characters, which is stretched
    with scrypt.

    Raises:
        ValueError: If the input is neither a hex key nor a long enough passphrase.
    """
    if not isinstance(key_text, str):
        raise ValueError("Key must be a string")
    key_text = key_text.strip()
    if _HEX_KEY_RE.match(key_text):
        return bytes.fromhex(key_text)
    if len(key_text) < MIN_PASSPHRASE_LENGTH:
        raise ValueError(
            f"Key must be 64 hex characters or a passphrase of at least {MIN_PASSPHRASE_LENGTH} characters"
        )
    kdf = Scrypt(salt=_PASSPHRASE_SALT, length=KEY_BYTES, n=2**15, r=8, p=1)
    return kdf.derive(key_text.encode("utf-8"))


def key_fingerprint(key: bytes) -> str:
    """Short fingerprint both operators can compare to check their keys match."""
    digest = hashlib.sha256(b"FreeDATA fingerprint" + key).hexdigest()[:16].upper()
    return " ".join(digest[i : i + 4] for i in range(0, len(digest), 4))


def encrypt(key: bytes, plaintext: bytes) -> bytes:
    """Encrypts plaintext with AES-256-GCM and a random nonce."""
    header = bytes([FORMAT_VERSION])
    nonce = os.urandom(NONCE_BYTES)
    return header + nonce + AESGCM(key).encrypt(nonce, bytes(plaintext), header)


def decrypt(key: bytes, payload: bytes) -> bytes:
    """Decrypts a payload created by encrypt().

    Raises:
        DecryptionError: On a wrong key, an unknown format version or corrupt data.
    """
    payload = bytes(payload)
    if len(payload) < OVERHEAD_BYTES:
        raise DecryptionError("Encrypted payload is too short")
    if payload[0] != FORMAT_VERSION:
        raise DecryptionError(f"Unknown encryption format version {payload[0]}")
    header = payload[:1]
    nonce = payload[1 : 1 + NONCE_BYTES]
    try:
        return AESGCM(key).decrypt(nonce, payload[1 + NONCE_BYTES :], header)
    except InvalidTag as e:
        raise DecryptionError("Wrong key or corrupted data") from e


def decrypt_any(keys, payload: bytes) -> bytes:
    """Decrypts a payload with the first of keys that fits.

    Raises:
        DecryptionError: If no key fits (or keys is empty).
    """
    for key in keys:
        try:
            return decrypt(key, payload)
        except DecryptionError:
            continue
    raise DecryptionError("Wrong key or corrupted data")


class StationKeyStore:
    """Thread-safe, in-memory store of pre-shared keys per station callsign,
    plus an optional common key for all stations."""

    def __init__(self, common_key_enabled=None):
        self._keys = {}
        self._common_key = None
        self._lock = threading.Lock()
        # returns True while the common key setting is on
        self._common_key_enabled = common_key_enabled or (lambda: False)

    def set(self, callsign: str, key: bytes):
        if len(key) != KEY_BYTES:
            raise ValueError("Invalid key length")
        with self._lock:
            self._keys[callsign] = bytes(key)

    def get(self, callsign: str):
        with self._lock:
            return self._keys.get(callsign)

    def has(self, callsign: str) -> bool:
        return self.get(callsign) is not None

    def remove(self, callsign: str) -> bool:
        with self._lock:
            return self._keys.pop(callsign, None) is not None

    def fingerprint(self, callsign: str):
        key = self.get(callsign)
        return key_fingerprint(key) if key else None

    def set_common(self, key: bytes):
        if len(key) != KEY_BYTES:
            raise ValueError("Invalid key length")
        with self._lock:
            self._common_key = bytes(key)

    def get_common(self):
        with self._lock:
            return self._common_key

    def remove_common(self) -> bool:
        with self._lock:
            removed = self._common_key is not None
            self._common_key = None
            return removed

    def common_fingerprint(self):
        key = self.get_common()
        return key_fingerprint(key) if key else None

    def common_enabled(self) -> bool:
        """True if the common key setting is on (whether or not the key is entered)."""
        return bool(self._common_key_enabled())

    def key_for(self, callsign: str):
        """The key to encrypt messages to callsign with: its own key, otherwise the
        common key if that setting is on. None if neither is available."""
        key = self.get(callsign)
        if key is None and self.common_enabled():
            key = self.get_common()
        return key

    def keys_for(self, callsign: str):
        """The keys to try when decrypting a message from or to callsign, own key first."""
        keys = [self.get(callsign)]
        if self.common_enabled():
            keys.append(self.get_common())
        return [key for key in keys if key is not None]
